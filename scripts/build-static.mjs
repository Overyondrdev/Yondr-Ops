// Bundles everything in public/ into the Worker script as src/static.generated.js (git-ignored).
// Why: `wrangler deploy` from Claude cloud sessions can't upload Workers static assets (see README "Deploy"), and
// bundling lets the Worker check the sign-in before serving any file.
// - Text files are embedded as strings, binary files (fonts, images) as base64.
// - In HTML, `?v=__HASH__` after a local path becomes that file's content hash (cache-busting for long caching).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PUBLIC = join(ROOT, 'public');
const OUT = join(ROOT, 'src', 'static.generated.js');
const LIMIT = 1024 * 1024; // keep the bundle far below the 3 MB free-plan Worker limit

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};
const TEXT = new Set(['.html', '.js', '.css', '.svg', '.txt', '.json']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const hash = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 16);

const files = walk(PUBLIC).filter((p) => !p.split(sep).pop().startsWith('.')).sort();
const raw = new Map(files.map((p) => ['/' + relative(PUBLIC, p).split(sep).join('/'), readFileSync(p)]));
const out = {};
let total = 0;
for (const [path, buf0] of raw) {
  const ext = extname(path).toLowerCase();
  if (!TYPES[ext]) throw new Error(`No content type for ${path}; add it to TYPES in scripts/build-static.mjs`);
  let buf = buf0;
  if (ext === '.html') {
    const html = buf.toString('utf8').replace(/(\/[\w./-]+)\?v=__HASH__/g, (m, ref) => {
      if (!raw.has(ref)) throw new Error(`${path} references ${ref}, which is not in public/`);
      return `${ref}?v=${hash(raw.get(ref))}`;
    });
    buf = Buffer.from(html, 'utf8');
  }
  total += buf.length;
  out[path] = TEXT.has(ext)
    ? { type: TYPES[ext], etag: `"${hash(buf)}"`, text: buf.toString('utf8') }
    : { type: TYPES[ext], etag: `"${hash(buf)}"`, base64: buf.toString('base64') };
}
if (total > LIMIT) throw new Error(`public/ is ${total} bytes; keep it under ${LIMIT} (Worker size limit).`);

writeFileSync(OUT, `// GENERATED by scripts/build-static.mjs from public/. Do not edit; run \`npm run build\`.\n` +
  `export const FILES = ${JSON.stringify(out, null, 0)};\n`);
console.log(`static: ${Object.keys(out).length} files, ${(total / 1024).toFixed(1)} KiB -> src/static.generated.js`);
